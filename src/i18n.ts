const TABLES: Record<Lang, Record<TextKey, string>> = { fi, en, th };

let current: Lang = 'fi';

export function setLang(l: Lang): void {
  current = l;
  if (typeof document !== 'undefined') document.documentElement.lang = l;
}

export function getLang(): Lang {
  return current;
}

export function isLang(v: unknown): v is Lang {
  return v === 'fi' || v === 'en' || v === 'th';
}

/** Text for a key in the current language, with {name} placeholders filled in. */
export function t(
  key: TextKey,
  vars: Record<string, string | number> = {},
  lang: Lang = current,
): string {
  const text = TABLES[lang][key] ?? fi[key];
  return text.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

/** Every key in every language (for tests). */
export function allTables(): Record<Lang, Record<TextKey, string>> {
  return TABLES;
}
